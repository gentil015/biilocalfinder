export function translateMessage(locale: LocaleCode, message: string): string {
  const key = messageKeyForEnglish(message);
  if (key) return MESSAGES[locale][key];
  if (locale !== 'rw') return message;
  const translated = PROVIDER_COPY_RW[message] ?? PROVIDER_COPY_RW_EXTRA[message];
  if (translated) return translated;

  const unread = message.match(/^Notifications, (\d+) unread$/);
  if (unread) return `Ubutumwa bumenyesha ${unread[1]} utarasoma`;
  const quoteAccepted = message.match(/^Your quote of (.+) was accepted\. A booking has been created — open it to see the agreed details\.$/);
  if (quoteAccepted) return `Igiciro cyawe cya ${quoteAccepted[1]} cyemewe. Gahunda yashyizweho — yifungure urebe ibisobanuro byumvikanyweho.`;
  const bookingCreated = message.match(/^Your booking with (.+) has been created at the agreed price of (.+)\.$/);
  if (bookingCreated) return `Gahunda yawe na ${bookingCreated[1]} yashyizweho ku giciro mwumvikanyeho cya ${bookingCreated[2]}.`;
  const providerApplicationApproved = message.match(/^(.+) is live\. Finish setting up your services to start receiving requests\.$/);
  if (providerApplicationApproved) return `${providerApplicationApproved[1]} yamaze gushyirwa ku rubuga. Rangiza gutunganya serivisi zawe kugira ngo utangire kwakira ubusabe.`;
  const bookingReminderClient = message.match(/^Your (.+) booking with (.+) is coming up on (.+)\.$/);
  if (bookingReminderClient) return `Gahunda yawe ya ${bookingReminderClient[1]} na ${bookingReminderClient[2]} iri hafi, ku wa ${bookingReminderClient[3]}.`;
  const bookingReminderProvider = message.match(/^You have a (.+) booking scheduled for (.+)\.$/);
  if (bookingReminderProvider) return `Ufite gahunda ya ${bookingReminderProvider[1]} iteganyijwe ku wa ${bookingReminderProvider[2]}.`;
  const priceProposal = message.match(/^A new price of (.+) RWF was proposed$/);
  if (priceProposal) return `Hatanzwe igiciro gishya cya ${priceProposal[1]} RWF`;
  const acceptedPrice = message.match(/^(.+) RWF was accepted$/);
  if (acceptedPrice) return `Igiciro cya ${acceptedPrice[1]} RWF cyemewe`;
  const messageName = message.match(/^New message on your dispute$/);
  if (messageName) return 'Ubutumwa bushya ku kibazo watanze';
  return message;
}

export function interpolate(template: string, values: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match,
  );
}

export function createFormatters(code: LocaleCode) {
  return {
    date: (value: Date | string | number, options?: Intl.DateTimeFormatOptions) =>
      new Intl.DateTimeFormat(code, options ?? { dateStyle: 'medium' }).format(new Date(value)),
    number: (value: number, options?: Intl.NumberFormatOptions) =>
      new Intl.NumberFormat(code, options).format(value),
  };
}